import {
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import {
  join,
  relative,
  resolve,
  sep,
} from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../../../", import.meta.url));
const OUTPUT = join(
  ROOT,
  "infra",
  "serverless-platform",
  "lambda",
  "journeys",
  "template-assets.mjs",
);
const EXCLUDED = new Set([
  ".cache",
  ".cli",
  ".git",
  ".venv",
  "__pycache__",
  "cdk.out",
  "dist",
  "node_modules",
]);

function walk(directory) {
  const files = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (EXCLUDED.has(entry.name)) continue;
    const absolute = join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...walk(absolute));
      continue;
    }
    if (
      entry.isSymbolicLink()
      || entry.name.endsWith(".pyc")
      || entry.name === "uv.lock"
      || entry.name === ".env.local"
    ) {
      continue;
    }
    const content = readFileSync(absolute, "utf8");
    if (content.includes("\u0000")) {
      throw new Error(`Journey template is not UTF-8 text: ${absolute}`);
    }
    files.push({ absolute, content });
  }
  return files;
}

function blueprintEntries(templateId) {
  const directory = join(ROOT, "blueprints", templateId);
  return walk(directory)
    .map(({ absolute, content }) => ({
      path: relative(directory, absolute).split(sep).join("/"),
      content: relative(directory, absolute).split(sep).join("/")
        === "agentcore/agentcore.json"
        ? portableAgentCoreConfig(content)
        : content,
      mode: "100644",
    }))
    .sort((left, right) => left.path.localeCompare(right.path));
}

function portableAgentCoreConfig(content) {
  const config = JSON.parse(content);
  for (const runtime of config.runtimes || []) {
    runtime.authorizerType = "AWS_IAM";
    delete runtime.authorizerConfiguration;
    delete runtime.requestHeaderAllowlist;
  }
  return `${JSON.stringify(config, null, 2)}\n`;
}

function ciEntries() {
  const directory = join(ROOT, "console", "ci-templates");
  const entries = walk(directory)
    .map(({ absolute, content }) => {
      const source = relative(directory, absolute).split(sep).join("/");
      const path = source.startsWith("gates/")
        ? source
        : `.github/workflows/${source}`;
      return [path, content];
    });
  entries.push([
    "gates/guardrail-chain.mjs",
    readFileSync(
      join(ROOT, "console", "public", "guardrail-chain.mjs"),
      "utf8",
    ),
  ]);
  return Object.fromEntries(
    entries.sort(([left], [right]) => left.localeCompare(right)),
  );
}

export function buildJourneyTemplateAssets() {
  return {
    blueprints: {
      chatagent: blueprintEntries("chatagent"),
      workflowagent: blueprintEntries("workflowagent"),
    },
    ci: ciEntries(),
  };
}

export function renderJourneyTemplateAssets(assets) {
  return [
    "// Generated by scripts/generate-journey-template-assets.mjs.",
    "// Do not edit by hand; the contract test compares this with the portable source projection.",
    `export const JOURNEY_TEMPLATES = Object.freeze(${JSON.stringify(assets)});`,
    "",
  ].join("\n");
}

export function writeJourneyTemplateAssets() {
  const content = renderJourneyTemplateAssets(buildJourneyTemplateAssets());
  writeFileSync(OUTPUT, content);
  return OUTPUT;
}

if (
  process.argv[1]
  && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))
) {
  process.stdout.write(`${writeJourneyTemplateAssets()}\n`);
}
